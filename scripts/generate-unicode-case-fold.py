#!/usr/bin/env python3
"""Generate the Java 25 region comparison table from UnicodeData 16.0.0."""

import argparse
import hashlib
from pathlib import Path

UNICODE_DATA_SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"
ROOT = Path(__file__).resolve().parent.parent


def fold_ranges(upper, lower):
    ranges = []
    for source in sorted(upper.keys() | lower.keys()):
        capital = upper.get(source, source)
        target = lower.get(capital, capital)
        if source == target:
            continue
        if (source > 0xFFFF) != (target > 0xFFFF):
            raise ValueError(f"case mapping changes the UTF-16 width of U+{source:04X}")
        delta = target - source
        if ranges and ranges[-1][3] == delta:
            start, end, stride, _ = ranges[-1]
            gap = source - end
            if (start == end and gap in (1, 2)) or gap == stride:
                ranges[-1] = (start, source, gap, delta)
                continue
        ranges.append((source, source, 1, delta))
    return ranges


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_data", type=Path)
    args = parser.parse_args()
    data = args.unicode_data.read_bytes()
    if hashlib.sha256(data).hexdigest() != UNICODE_DATA_SHA256:
        parser.error("expected UnicodeData.txt from Unicode 16.0.0")
    upper = {}
    lower = {}
    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        code_point = int(fields[0], 16)
        if fields[12]:
            upper[code_point] = int(fields[12], 16)
        if fields[13]:
            lower[code_point] = int(fields[13], 16)
    ranges = fold_ranges(upper, lower)
    license_lines = (ROOT / "src/main/resources/META-INF/LICENSE-UNICODE-3.0.txt").read_text(encoding="utf-8").splitlines()
    print("""package javan.codegen;

final class Unicode16CaseFold {
    // Generated by scripts/generate-unicode-case-fold.py.
    static final String SOURCE = """
        + '"""')
    print("        /*")
    print("         * Data derived from https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt.")
    print("         * SPDX-License-Identifier: Unicode-3.0")
    for line in license_lines:
        print("         *" + (" " + line if line else ""))
    print("         */")
    print("        static const struct { int first, last, stride, delta; } javan_unicode_case_folds[] = {")
    for first, last, stride, delta in ranges:
        print(f"            {{0x{first:04X}, 0x{last:04X}, {stride}, {delta}}},")
    print("""        };
        """ + '""";' + """

    private Unicode16CaseFold() {
    }
}""")


if __name__ == "__main__":
    main()
